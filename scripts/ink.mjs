// Generates the hand-drawn outline tokens in public/app.css (between the INK markers).
// Run: node scripts/ink.mjs   (dev only; output is plain CSS, nothing runs in the browser)
//
// Idea (after Looseleaf, MIT, kevintngo.github.io/looseleaf): a pen outline is drawn once per seed into a
// 48×48 SVG and used as a 9-slice `border-image`. Corners keep their drawn shape, the edge slices stretch
// into a long, gentle wobble, so any box (button, input, card) gets an outline at its real size, in CSS only.
// Every random choice comes from a seeded generator: same seed, same line, stable screenshots.
import { readFileSync, writeFileSync } from 'node:fs';

const S = 48; // tile size
const IN = 6; // stroke sits 6px in from the tile edge (= border-image-outset, so the line lands on the box edge)

function rng(seed) {
  let s = seed >>> 0;
  return () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296);
}

/** Rounded rectangle walked clockwise with small wobbles, a slight corner lean and an overlapping pen lift. */
function outline(seed, r = 5, wob = 0.55) {
  const R = rng(seed);
  const j = (a = wob) => (R() * 2 - 1) * a;
  const a = IN, b = S - IN;
  const f = (n) => n.toFixed(2);
  // start a little into the top edge; finish past it so the stroke overlaps like a real pen
  const start = [a + r + 3 + j(1), a + j()];
  const pts = [
    `M${f(start[0])} ${f(start[1])}`,
    `Q${f(S / 2)} ${f(a + j())} ${f(b - r)} ${f(a + j(0.4))}`,
    `Q${f(b + j(0.6))} ${f(a + j(0.6))} ${f(b + j(0.4))} ${f(a + r)}`,
    `Q${f(b + j())} ${f(S / 2)} ${f(b + j(0.4))} ${f(b - r)}`,
    `Q${f(b + j(0.6))} ${f(b + j(0.6))} ${f(b - r)} ${f(b + j(0.4))}`,
    `Q${f(S / 2)} ${f(b + j())} ${f(a + r)} ${f(b + j(0.4))}`,
    `Q${f(a + j(0.6))} ${f(b + j(0.6))} ${f(a + j(0.4))} ${f(b - r)}`,
    `Q${f(a + j())} ${f(S / 2)} ${f(a + j(0.4))} ${f(a + r)}`,
    `Q${f(a + j(0.6))} ${f(a + j(0.6))} ${f(a + r)} ${f(a + j(0.4))}`,
    `L${f(start[0] + 4 + R() * 3)} ${f(start[1] + j(0.7))}`,
  ];
  return pts.join('');
}

function svg(d, color, width) {
  const s = `<svg xmlns='http://www.w3.org/2000/svg' width='${S}' height='${S}' viewBox='0 0 ${S} ${S}'><path d='${d}' fill='none' stroke='${color}' stroke-width='${width}' stroke-linecap='round' stroke-linejoin='round'/></svg>`;
  return `url("data:image/svg+xml,${s.replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E')}")`;
}

const SEEDS = { a: 11, b: 29, c: 47 };
const PENS = {
  // name: [light color, dark color, width]
  ink: ['#2a2420', '#e9e1d3', 1.8], // dark felt-tip: controls, outlines
  pencil: ['#8e887f', '#8a8378', 1.3], // pencil: quiet boxes, ghost buttons, fields
  red: ['#c2412d', '#ff8f7a', 1.8], // red pencil: invalid / danger
};

const light = [], dark = [];
for (const [pen, [lc, dc, w]] of Object.entries(PENS))
  for (const [k, seed] of Object.entries(SEEDS)) {
    const d = outline(seed + pen.length * 101);
    light.push(`  --ink-${pen}-${k}: ${svg(d, lc, w)};`);
    dark.push(`    --ink-${pen}-${k}: ${svg(d, dc, w)};`);
  }

const block = `/* INK:BEGIN generated by scripts/ink.mjs, do not edit by hand */
:root {
${light.join('\n')}
}
@media (prefers-color-scheme: dark) {
  :root {
${dark.join('\n')}
  }
}
/* INK:END */`;

const file = new URL('../public/app.css', import.meta.url);
const css = readFileSync(file, 'utf8');
const re = /\/\* INK:BEGIN[\s\S]*?INK:END \*\//;
writeFileSync(file, re.test(css) ? css.replace(re, block) : `${css.trimEnd()}\n\n${block}\n`);
console.log(`ink: ${light.length} outlines written (${Object.keys(PENS).length} pens × ${Object.keys(SEEDS).length} seeds)`);
